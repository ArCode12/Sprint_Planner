      <h2>What is sprint planning?</h2>
      <p>
        Sprint planning is a short meeting at the start of a work cycle — usually one to
        two weeks — where a team decides what to build, fix, or finish next. Instead of
        one long, vague to-do list, the work gets broken into a small, realistic batch
        the team can actually commit to.
      </p>
      <p>
        The goal isn't just to assign tasks — it's to make sure everyone agrees on
        priorities, understands what "done" actually looks like, and has a realistic
        sense of how much can genuinely get finished in the time available.
      </p>
      <h3>Why teams use it</h3>
      <p>
        Without planning, work tends to arrive in a constant, unstructured stream —
        it's hard to tell what's urgent, what's already in progress, or what's
        forgotten. Sprint planning gives that work shape: a clear starting point, a
        clear stopping point, and a shared board everyone can check instead of asking
        around.
      </p>
